import assert from 'node:assert/strict';
import { readFile, writeFile, mkdir, copyFile, readdir, stat } from 'node:fs/promises';
import { spawn } from 'node:child_process';
import { once } from 'node:events';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { scanPaths, isIgnored, collectFile, atomicWrite, acquireWatchLock } from './brain-core.mjs';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const fixture=path.join(root,'.mythreon-brain','tests','check-'+Date.now());
await mkdir(path.join(fixture,'src'),{recursive:true});
await mkdir(path.join(fixture,'release'),{recursive:true});
await mkdir(path.join(fixture,'assets'),{recursive:true});
await writeFile(path.join(fixture,'src/example.ts'),'export const answer=42;');
await writeFile(path.join(fixture,'release/electron.exe'),'arquivo que não pode entrar no índice');
await writeFile(path.join(fixture,'root.EXE'),'ignorar também por extensão');
await writeFile(path.join(fixture,'.env'),'PRIVATE=not-real');
await writeFile(path.join(fixture,'assets/picture.png'),Buffer.alloc(32));
assert.ok(isIgnored('ReLeAsE/electron.exe'));assert.ok(isIgnored('root.EXE'));assert.ok(isIgnored('.env.local'));
const scan=await scanPaths(fixture);
assert.ok(scan.files.every(file=>!file.endsWith('.exe')&&!file.endsWith('.EXE')&&!file.endsWith('.env')));
const old={hash:'preserved',bytes:0,mtime:0,meta:{symbols:['old'],dependencies:[],headings:[]}};
const warnings=[];
const locked={stat,readFile:async()=>{throw Object.assign(new Error('locked'),{code:'EBUSY'});}};
const kept=await collectFile(path.join(fixture,'src/example.ts'),old,()=>{},warnings,locked);
assert.equal(kept.hash,'preserved');assert.equal(warnings[0].code,'EBUSY');
assert.equal(await collectFile(path.join(fixture,'src/example.ts'),null,()=>{},[],locked),null);
const asset=await collectFile(path.join(fixture,'assets/picture.png'),null,()=>{throw new Error('Não extrair asset');},[],{stat,readFile:async()=>{throw new Error('Não abrir asset');}});
assert.ok(asset.hash.startsWith('metadata:'));
const original='# Regra original\nNão sobrescrever o conhecimento.\n';
await mkdir(path.join(fixture,'docs/conhecimento'),{recursive:true});
await writeFile(path.join(fixture,'docs/conhecimento/Minha nota.md'),original);
await writeFile(path.join(fixture,'CEREBRO_MYTHREON.md'),'# Cérebro original\n');
await mkdir(path.join(fixture,'Mythreon Obsidian'),{recursive:true});
await writeFile(path.join(fixture,'Mythreon Obsidian/CEREBRO_MYTHREON.md'),'# Cópia antiga preservada\n');
const output=path.join(fixture,'generated.json');
await atomicWrite(output,'primeiro');await atomicWrite(output,'segundo');const before=(await stat(output)).mtimeMs;
assert.equal(await atomicWrite(output,'segundo'),false);assert.equal((await stat(output)).mtimeMs,before);
const lockDir=path.join(fixture,'.mythreon-brain');
const lock=await acquireWatchLock(lockDir);assert.ok(lock);assert.equal(await acquireWatchLock(lockDir),null);await lock.release();
await mkdir(path.join(fixture,'scripts'),{recursive:true});
for(const name of ['mythreon-brain.mjs','brain-core.mjs','brain-service.mjs'])await copyFile(path.join(root,'scripts',name),path.join(fixture,'scripts',name));
const sleep=ms=>new Promise(resolve=>setTimeout(resolve,ms));
async function until(check,timeout=12000){const end=Date.now()+timeout;while(Date.now()<end){try{if(await check())return;}catch{}await sleep(100);}throw new Error('Timeout aguardando observador');}
let logs='';
const service=spawn(process.execPath,[path.join(fixture,'scripts/brain-service.mjs')],{cwd:fixture,stdio:['ignore','pipe','pipe','ipc']});
service.stdout.on('data',chunk=>{logs+=chunk.toString();});service.stderr.on('data',chunk=>{logs+=chunk.toString();});
const readIndex=async()=>JSON.parse(await readFile(path.join(fixture,'.mythreon-brain/neurons.json'),'utf8'));
try {
  await until(()=>logs.includes('Observando arquivos e notas'));
  const index=await readIndex();assert.ok(index.files.every(row=>!isIgnored(row[0])));
  assert.equal(await readFile(path.join(fixture,'docs/conhecimento/Minha nota.md'),'utf8'),original);
  assert.equal(await readFile(path.join(fixture,'CEREBRO_MYTHREON.md'),'utf8'),'# Cérebro original\n');
  const archiveFolders=await readdir(path.join(fixture,'Mythreon Obsidian/Arquivo'));
  assert.equal(await readFile(path.join(fixture,'Mythreon Obsidian/Arquivo',archiveFolders[0],'Cerebro legado - copia gerada.md'),'utf8'),'# Cópia antiga preservada\n');
  let duplicateLog='';const duplicate=spawn(process.execPath,[path.join(fixture,'scripts/mythreon-brain.mjs'),'--watch'],{cwd:fixture,stdio:['ignore','pipe','pipe']});duplicate.stdout.on('data',chunk=>duplicateLog+=chunk.toString());
  await once(duplicate,'close');assert.ok(duplicateLog.includes('Já existe'));
  await writeFile(path.join(fixture,'src/new.ts'),'export const next=1;');
  await writeFile(path.join(fixture,'release/electron.exe'),'continua fora do índice');
  await until(async()=>(await readIndex()).files.some(row=>row[0]==='src/new.ts'));
  await writeFile(path.join(fixture,'scripts/brain-core.mjs'),(await readFile(path.join(fixture,'scripts/brain-core.mjs'),'utf8'))+'\n// teste de recarga\n');
  await until(()=>(logs.match(/Observando arquivos e notas/g)??[]).length>=2);
  assert.ok(logs.includes('recarregando as novas regras'));
  await writeFile(path.join(fixture,'src/after-reload.ts'),'export const latest=true;');
  await until(async()=>(await readIndex()).files.some(row=>row[0]==='src/after-reload.ts'));
  const status=JSON.parse(await readFile(path.join(fixture,'.mythreon-brain/status.json'),'utf8'));assert.equal(status.status,'ok');
  assert.equal(await readFile(path.join(fixture,'docs/conhecimento/Minha nota.md'),'utf8'),original);
  assert.ok(!(await readIndex()).files.some(row=>row[0].startsWith('release/')));
  console.log('PASS: release/binários/segredos ignorados; EBUSY preserva índice; assets não são abertos; gravação por substituição; notas preservadas; cópia legada arquivada; lock evita duplicatas; eventos e recarga automática funcionam.');
} finally {
  if(service.connected)service.send('stop');
  await Promise.race([once(service,'close'),sleep(3000)]);
  if(service.exitCode===null)service.kill('SIGTERM');
}
